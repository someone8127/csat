#!/usr/bin/env node
/**
 * data/src/**\/*.json (시험지 단위 원본)  →  data/bank.js (사이트가 읽는 문제은행)
 *
 *  - 문제 번호로 유형(typeKey)을 자동 판정 (js/config.js 의 TYPES 기준, "type" 필드로 덮어쓰기 가능)
 *  - 문항 ID 자동 생성:  {exam.id}-{number}   예) 2025-06-g3-31
 *  - 형식 검증(선지 5개, 정답 1~5, 필수 필드, 중복 ID 등) 후 하나라도 오류면 중단
 *
 * 사용:  node tools/build-bank.mjs   (또는 npm run build:data)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const CFG = require("../js/config.js");

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "data", "src");
const OUT = path.join(ROOT, "data", "bank.js");

const errors = [];
const warns = [];
const err = (f, msg) => errors.push(`[ERROR] ${f}: ${msg}`);
const warn = (f, msg) => warns.push(`[WARN ] ${f}: ${msg}`);

function walk(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const p = path.join(dir, d.name);
    if (d.isDirectory()) return walk(p);
    return d.name.endsWith(".json") && !d.name.startsWith("_") ? [p] : [];
  });
}

const CIRCLED = /^\s*[①②③④⑤]\s*/;
const bank = [];
const seen = new Set();
let skippedTodo = 0;

for (const file of walk(SRC)) {
  const rel = path.relative(ROOT, file);
  let doc;
  try {
    doc = JSON.parse(fs.readFileSync(file, "utf8"));
  } catch (e) {
    err(rel, "JSON 문법 오류 - " + e.message);
    continue;
  }

  const ex = doc.exam || {};
  if (!ex.id) err(rel, "exam.id 가 없습니다 (예: 2025-06-g3)");
  if (!CFG.GRADES.includes(ex.grade)) err(rel, `exam.grade 는 ${CFG.GRADES.join("/")} 중 하나여야 합니다 (현재: ${ex.grade})`);
  if (!ex.label) warn(rel, "exam.label 이 없습니다 (화면에 표시되는 시험 이름)");
  if (!Array.isArray(doc.questions)) { err(rel, "questions 배열이 없습니다"); continue; }

  const byNumber = new Map(doc.questions.map((q) => [q.number, q]));

  for (const q of doc.questions) {
    const where = `${rel} #${q.number}`;
    if (q.status === "todo") { skippedTodo++; continue; }

    if (!Number.isInteger(q.number) || q.number < 18 || q.number > 45) { err(where, "number 는 18~45 정수여야 합니다"); continue; }

    const typeKey = q.type || CFG.typeKeyByNumber(q.number);
    if (!CFG.typeByKey(typeKey)) { err(where, `알 수 없는 type: ${typeKey}`); continue; }

    let passage = q.passage || "";
    if (q.sharedWith != null) {
      const src = byNumber.get(q.sharedWith);
      if (!src || !src.passage) err(where, `sharedWith ${q.sharedWith}번의 passage 를 찾을 수 없습니다`);
      else passage = src.passage;
    }

    if (!q.title) err(where, "title(발문)이 없습니다");
    if (!passage && !q.image) err(where, "passage 또는 image 가 필요합니다");
    if (!Array.isArray(q.options) || q.options.length !== 5 || q.options.some((o) => typeof o !== "string" || !o.trim()))
      err(where, "options 는 비어 있지 않은 문자열 5개여야 합니다");
    if (!Number.isInteger(q.answer) || q.answer < 1 || q.answer > 5) err(where, "answer 는 1~5 정수여야 합니다");
    if (!q.explanation) warn(where, "explanation(해설)이 비어 있습니다");
    if (!q.translation) warn(where, "translation(번역)이 비어 있습니다");
    if (q.image && !fs.existsSync(path.join(ROOT, q.image))) err(where, `image 파일이 없습니다: ${q.image}`);

    const id = `${ex.id}-${q.number}`;
    if (seen.has(id)) { err(where, `중복 ID: ${id}`); continue; }
    seen.add(id);

    bank.push({
      id,
      examId: ex.id,
      examLabel: ex.label || ex.id,
      grade: ex.grade,
      typeKey,
      number: q.number,
      title: q.title,
      passage,
      image: q.image || undefined,
      options: (q.options || []).map((o) => String(o).replace(CIRCLED, "")),
      answer: q.answer,
      explanation: q.explanation || "",
      translation: q.translation || "",
    });
  }
}

if (errors.length) {
  console.error(errors.join("\n"));
  console.error(`\n오류 ${errors.length}건 - data/bank.js 를 갱신하지 않았습니다.`);
  process.exit(1);
}

const gradeOrder = (g) => CFG.GRADES.indexOf(g);
bank.sort((a, b) => gradeOrder(a.grade) - gradeOrder(b.grade) || a.examId.localeCompare(b.examId) || a.number - b.number);

const banner = `/* AUTO-GENERATED by tools/build-bank.mjs - 직접 수정하지 마세요 (원본: data/src/*.json) */\n`;
fs.writeFileSync(OUT, banner + "window.QUESTION_BANK = " + JSON.stringify(bank, null, 1) + ";\n");

if (warns.length) console.warn(warns.join("\n") + "\n");
console.log(`data/bank.js 생성 완료: 총 ${bank.length}문항` + (skippedTodo ? ` (미작성 todo ${skippedTodo}문항 제외)` : ""));
for (const g of CFG.GRADES) {
  const n = bank.filter((q) => q.grade === g).length;
  if (n) console.log(`  ${g}: ${n}문항`);
}
for (const t of CFG.TYPES) {
  const n = bank.filter((q) => q.typeKey === t.key).length;
  console.log(`  [${t.range.padEnd(5)}] ${t.name}: ${n}문항`);
}
